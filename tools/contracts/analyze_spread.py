"""The timing spread behind every speedup in the paper.

A speedup is a ratio of two medians. This script states how wide the runs
behind those medians were, so that a reader can tell a ratio of 1.05 that is
noise from one that is not.

Reads
    results/contracts/e2e.jsonl                 RQ4 on M1 (p25, median, p75 of each build's runs)
    results/contracts-linux/e2e.jsonl           RQ4 on M2, GCC
    results/contracts-linux-clang/e2e.jsonl     RQ4 on M2, Clang
    results/contracts/e2e_real.jsonl            RQ4 on real data, M2
    results/contracts/llvm_bench.jsonl          RQ7 (one median per process)

and writes
    paper/generated/spread.tex          LaTeX macros (\\Spread...), in percent

    python tools/contracts/analyze_spread.py
"""

import json
import statistics
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402

ROOT = common.ROOT
RESULTS = ROOT / "results"
GEN = ROOT / "paper" / "generated"


def records(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


# Short builds are the noisy ones; the paper also states the spread of the rest.
LONG_NS = 10e6


def run_spread(paths):
    """(median ns, interquartile range of the build's runs relative to its median)."""
    out = []
    for path in paths:
        for r in records(path):
            if r.get("median_ns") and r.get("p25_ns") is not None and r.get("p75_ns") is not None:
                out.append((r["median_ns"], (r["p75_ns"] - r["p25_ns"]) / r["median_ns"]))
    return out


def process_spread(path):
    """(median ns, interquartile range of the per-process medians relative to the median)."""
    out = []
    for r in records(path):
        q1, _, q3 = statistics.quantiles(r["process_medians_ns"], n=4, method="inclusive")
        out.append((r["median_ns"], (q3 - q1) / r["median_ns"]))
    return out


def pct(x):
    return f"{100 * x:.0f}"


def main():
    groups = {
        "First": run_spread([RESULTS / "contracts" / "e2e.jsonl"]),
        "Second": run_spread([RESULTS / "contracts-linux" / "e2e.jsonl",
                              RESULTS / "contracts-linux-clang" / "e2e.jsonl",
                              RESULTS / "contracts" / "e2e_real.jsonl"]),
        "Llvm": process_spread(RESULTS / "contracts" / "llvm_bench.jsonl"),
    }
    m = {}
    for name, pairs in groups.items():
        assert pairs, f"no timing records for {name}"
        values = [s for _, s in pairs]
        long = [s for t, s in pairs if t >= LONG_NS]
        m[f"Spread{name}Builds"] = str(len(values))
        m[f"Spread{name}Median"] = pct(statistics.median(values))
        m[f"Spread{name}Max"] = pct(max(values))
        m[f"Spread{name}MaxLong"] = pct(max(long))
    GEN.mkdir(parents=True, exist_ok=True)
    lines = ["% Generated by tools/contracts/analyze_spread.py. Do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    (GEN / "spread.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"spread: {len(m)} macros")
    for k, v in sorted(m.items()):
        print(f"  {k} = {v}")


if __name__ == "__main__":
    main()
